const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const core=require('../extension/core.js');
const entries=['glossary.json','code-explanations.json'].flatMap(file=>JSON.parse(fs.readFileSync(path.join(root,'data',file),'utf8')));
const chapters=JSON.parse(fs.readFileSync(path.join(root,'data/chapters.json'),'utf8'));
const sources=JSON.parse(fs.readFileSync(path.join(root,'data/sources.json'),'utf8'));
core.validate(entries);
// Auto links are resolved at display time, including new personal entries.
core.validate(entries);
for(const c of chapters) for(const id of c.prerequisites) if(!entries.some(e=>e.id===id)) throw Error('章の参照先が不明: '+id);
fs.writeFileSync(path.join(root,'extension/data.js'),'/* Generated by node scripts/build.cjs. Edit data/*.json instead. */\nglobalThis.OSRGData = '+JSON.stringify({version:1,entries,chapters,sources})+';\n');
fs.copyFileSync(path.join(root,'extension/ai.js'),path.join(root,'native/ai.js'));
console.log(`${entries.length} entries, ${chapters.length} chapters; reference DAG valid`);

const corpus=chapters.map(c=>({number:c.number,text:fs.readFileSync(path.join(root,'research/original/ja',(c.number?c.slug:'index')+'.md'),'utf8')}));
fs.writeFileSync(path.join(root,'extension/chapter-text.js'),'globalThis.OSRGChapterText = '+JSON.stringify(corpus)+';\n');
